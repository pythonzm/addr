function detectLang() {
  const saved = localStorage.getItem('addr_lang');
  if (saved && I18N[saved]) return saved;
  const nav = navigator.language || 'zh-CN';
  if (/^zh/i.test(nav)) return /TW|HK|MO|Hant/i.test(nav) ? 'zh-TW' : 'zh-CN';
  if (/^ja/i.test(nav)) return 'ja';
  if (/^ko/i.test(nav)) return 'ko';
  return 'en';
}

let LANG = detectLang();

const t = key => (I18N[LANG] && I18N[LANG][key]) ?? I18N['zh-CN'][key] ?? key;

// 国家显示名：中文界面用中文名，其余语言（英/日/韩）用英文名
const countryDisplayName = c => (LANG === 'zh-CN' || LANG === 'zh-TW' ? c.name : c.en);

function applyI18n() {
  const nCountries = (typeof COUNTRIES !== 'undefined') ? Object.keys(COUNTRIES).length : '';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = String(t(el.dataset.i18n)).replace('{n}', nCountries);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.documentElement.lang = LANG;
  document.title = t('page_title');
  const sel = document.getElementById('langSelect');
  if (sel) sel.value = LANG;
}

function setLang(lang) {
  if (!I18N[lang]) return;
  LANG = lang;
  localStorage.setItem('addr_lang', lang);
  applyI18n();
  if (typeof window.onLangChange === 'function') window.onLangChange();
}

window.addEventListener('DOMContentLoaded', applyI18n);
